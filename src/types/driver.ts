import { ApiDocument } from './document';
import { PaginationMeta, SortOrder } from './transaction';

export type DriverStatus = 'ACTIVE' | 'INACTIVE' | 'SUSPENDED';
export type DriverSortBy = 'name' | 'status' | 'created_at';

export type DriverSummary = {
  id: string;
  name: string;
  surnames: string;
  status: DriverStatus;
  photo?: string | null;
};

export type DriversResponse = {
  drivers: DriverSummary[];
  pagination: PaginationMeta;
};

export type DriversParams = {
  page?: number;
  limit?: number;
  status?: DriverStatus;
  search?: string;
  archived?: boolean;
  sortBy?: DriverSortBy;
  sortOrder?: SortOrder;
};

export type Guarantor = {
  id: number;
  name: string;
  surnames: string;
  telephones: string[];
  address: string;
  relation: string;
  documents: ApiDocument[];
};

export type AssignedCar = {
  id: string;
  make: string;
  model: string;
  plate: string;
  agencyImage?: string | null;
};

/** The driver as returned by create / update / status / archive endpoints. */
export type DriverRecord = DriverSummary & {
  telephones: string[];
  licenseNumber: string;
  licenseValidity: string;
  identificationNumber: string;
  address: string;
  garageAddress: string[];
  createdAt: string;
  updatedAt: string;
  archivedAt?: string | null;
};

export type DriverDetail = DriverRecord & {
  documents: ApiDocument[];
  guarantors: Guarantor[];
  assignedCar?: AssignedCar | null;
};

/** POST /management/drivers. The id (folio) is generated by the backend. */
export type DriverCreate = {
  name: string;
  surnames: string;
  status: DriverStatus;
  telephones: string[];
  licenseNumber: string;
  /** ISO datetime with timezone (naive datetimes are rejected). */
  licenseValidity: string;
  identificationNumber: string;
  address: string;
  garageAddress: string[];
};

/** PATCH /management/drivers/{id}: only the changed fields. `photo: null` clears the photo; `status` has its own endpoint. */
export type DriverUpdate = Partial<Omit<DriverCreate, 'status'>> & { photo?: string | null };

export type GuarantorCreate = {
  name: string;
  surnames: string;
  telephones: string[];
  address: string;
  relation: string;
};
export type GuarantorUpdate = Partial<GuarantorCreate>;

/** Response of the guarantor endpoints (no documents; those come with the driver detail). */
export type GuarantorRecord = Omit<Guarantor, 'documents'> & { createdAt: string; updatedAt: string };
